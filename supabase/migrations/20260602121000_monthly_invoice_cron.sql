create extension if not exists pg_cron;

create unique index if not exists charges_auto_monthly_customer_idx
  on public.charges(customer_id, charge_date, charge_type)
  where invoice_reference like 'AUTO-%';

create or replace function public.generate_monthly_customer_charges(
  p_billing_month date default date_trunc('month', current_date)::date
)
returns table(customer_id uuid, charge_id uuid)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  billing_month date := date_trunc('month', coalesce(p_billing_month, current_date))::date;
  due_on date := (date_trunc('month', coalesce(p_billing_month, current_date))::date + interval '14 days')::date;
begin
  return query
  with created as (
    insert into public.charges (
      customer_id,
      pricing_item_id,
      charge_type,
      description,
      amount,
      currency,
      billing_status,
      invoice_reference,
      charge_date,
      due_date,
      notes
    )
    select
      customer.id,
      pricing.id,
      'monthly',
      trim(to_char(billing_month, 'FMMonth YYYY')) || ' Rex subscription',
      customer.recurring_monthly_amount,
      'GBP',
      'open',
      'AUTO-' || to_char(billing_month, 'YYYYMM') || '-' || left(customer.id::text, 8),
      billing_month,
      due_on,
      'Generated by Supabase invoice cron.'
    from public.customers customer
    left join public.pricing_items pricing
      on pricing.code = 'rex-main-license'
    where customer.status in ('active', 'at_risk')
      and customer.recurring_monthly_amount > 0
      and not exists (
        select 1
        from public.charges existing
        where existing.customer_id = customer.id
          and existing.charge_type = 'monthly'
          and existing.charge_date = billing_month
          and existing.invoice_reference = 'AUTO-' || to_char(billing_month, 'YYYYMM') || '-' || left(customer.id::text, 8)
      )
    returning public.charges.customer_id, public.charges.id, public.charges.description, public.charges.amount, public.charges.currency, public.charges.billing_status
  ), timeline as (
    insert into public.customer_timeline_items (
      customer_id,
      item_type,
      title,
      body,
      related_table,
      related_id,
      metadata
    )
    select
      created.customer_id,
      'charge',
      'Monthly invoice charge generated',
      created.description || ' - ' || created.currency || ' ' || to_char(created.amount, 'FM999999999990.00'),
      'charges',
      created.id,
      jsonb_build_object(
        'source', 'invoice_cron',
        'billing_status', created.billing_status,
        'billing_month', billing_month
      )
    from created
  )
  select created.customer_id, created.id
  from created;
end;
$$;

do $$
begin
  perform cron.unschedule('rex-monthly-invoice-charges');
exception
  when others then
    null;
end;
$$;

select cron.schedule(
  'rex-monthly-invoice-charges',
  '0 6 1 * *',
  $$select public.generate_monthly_customer_charges();$$
);
